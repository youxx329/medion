-- 대분류 9 + 중분류 25 = 34개
-- ============================================================
-- 설계 기준
--   계층은 2단계까지만. parent_id 가 null 이면 대분류.
--   3단계(예: 비타민 > 비타민C)는 만들지 않는다.
--   상품이 78개 규모라 계층을 더 파면 카테고리당 1개 미만이 된다.
--
--   sort_order 는 대분류마다 10 부터 다시 센다.
--   parent_id 로 이미 그룹이 나뉘므로 정렬은 그룹 안에서만 의미가 있고,
--   전체 통합 번호를 쓰면 중간에 하나 추가할 때 뒤가 전부 밀린다.
--
--   분류 기준은 성분 계열이 아니라 사용자가 찾는 목적이다.
--   "항산화제"는 약사 용어라 제외했다. 사용자는 "비타민"을 찾는다.
--
-- 편성 근거
--   material-names.json 에서 중분류별 대표 성분 건수를 미리 세어
--   상품을 채울 수 없는 분류는 만들지 않았다.
--     근이완  → 클로르족사존/에페리손이 전문약이라 0건. 소염진통에 흡수
--     다이어트 → 오르리스타트 전문약, 가르시니아 건기식. 삭제
--   엽산·철분은 건기식이라 health_foods 적재 후 상품이 붙는다.
--
--   실제 약국 매대와 완전히 일치시키지 않았다.
--   DUR 검사는 성분 단위로 이루어져 카테고리 수가 검증에 영향을 주지 않고,
--   분류를 늘리면 빈 카테고리가 생겨 탐색 경험이 나빠진다.
-- ============================================================

