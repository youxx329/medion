-- 대분류별 중분류 수
select
  p.sort_order,
  p.name as 대분류,
  count(c.id) as 중분류수
from categories p
left join categories c on c.parent_id = p.id
where p.parent_id is null
group by p.id, p.sort_order, p.name
order by p.sort_order;

-- join 실패 감지. 33이 나와야 정상
select count(*) from categories where parent_id is not null;

-- 화면 순서대로 전체 확인
select
  coalesce(p.name, c.name) as 대분류,
  case when p.name is null then null else c.name end as 중분류
from categories c
left join categories p on p.id = c.parent_id
order by coalesce(p.sort_order, c.sort_order), c.parent_id nulls first, c.sort_order;
