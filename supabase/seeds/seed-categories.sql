-- 설계 기준
--   계층은 2단계까지만. parent_id 가 null 이면 대분류.
--   3단계(예: 비타민 > 비타민C)는 만들지 않는다.
--
--   sort_order 는 대분류마다 10 부터 다시 센다.
--   parent_id 로 이미 그룹이 나뉘므로 정렬은 그룹 안에서만 의미가 있고,
--   전체 통합 번호를 쓰면 중간에 하나 추가할 때 뒤가 전부 밀린다.
--
--   분류 기준은 성분 계열이 아니라 사용자가 찾는 목적이다.
--   "항산화제"는 약사 용어라 제외했다. 사용자는 "비타민"을 찾는다.
--
-- 상품 범위
--   일반 약국은 전문의약품·일반의약품·건강기능식품·일반식품을 함께 취급한다.
--   메디온은 이 중 일반의약품과 건강기능식품만 다룬다.
--   식약처가 성분 코드를 부여한 범위가 여기까지이고,
--   DUR 검증이 불가능한 상품을 온라인 약국에 올리는 것은 서비스 취지에 맞지 않는다.
--
--   그 결과 실제 매대에 있는 일부 상품이 빠졌다.
--   숙취해소제가 대표적이다. 약국 판매 상위 5종 중 4종이 일반식품이라
--   두 API 어디에도 없었다. 일반식품 API를 추가하면 채울 수 있지만,
--   DUR 대상이 아닌 상품을 늘리는 것이라 얻는 것이 없다고 판단해 제외했다.
--
-- 편성 근거
--   실제 근무 약국의 판매 품목을 먼저 나열하고, 그 목록에서 분류를 역산했다.
--   분류를 먼저 만들고 API 검색으로 채우면 상품 구성이 검색 결과에 끌려간다.-
--
-- 쪼갠 것과 이유
--   밴드·소독 → 밴드 / 소독약
--     제형 필터가 무의미한 분류다. 둘 다 외용이라 필터가 작동하지 않고,
--     사용자가 알고 싶은 것은 "밴드냐 소독약이냐"다.
--   구충·멀미 → 구충 / 멀미
--     상품 수는 각 3~4개로 적지만, 사용자가 두 목적을 혼동한다.
--   숙취·피로 → 숙취 / 피로회복
--     매대가 다르고 사용 맥락이 다르다.
--     숙취는 음주 전후, 피로회복은 액상 즉효 제품이다.
--   비타민 / 피로회복 경계는 성분이 아니라 제형으로 갈랐다.
--     정제를 꾸준히 먹는 것(아로나민·임팩타민)과
--     액상을 그날 마시는 것(가네스·활비톤)은 사용자 인식이 다르다.
-- ============================================================

