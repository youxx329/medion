-- 대분류별 증상 수
select c.sort_order, c.name as 대분류, count(s.id) as 증상수
from categories c
left join symptoms s on s.category_id = c.id
where c.parent_id is null
group by c.id, c.sort_order, c.name
order by c.sort_order;

